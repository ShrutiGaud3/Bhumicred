export const getDistricts = (countryName = 'India (Bharat)', stateName) => {
  const resolvedCountry = WORLD_GEOGRAPHY[countryName] ? countryName : 'India (Bharat)';
  if (!stateName || !WORLD_GEOGRAPHY[resolvedCountry]?.[stateName]) {
    const firstState = Object.keys(WORLD_GEOGRAPHY[resolvedCountry] || {})[0];
    return firstState ? Object.keys(WORLD_GEOGRAPHY[resolvedCountry][firstState]) : [];
  }
  return Object.keys(WORLD_GEOGRAPHY[resolvedCountry][stateName]);
};

export const getCities = (countryName = 'India (Bharat)', stateName, districtName) => {
  const resolvedCountry = WORLD_GEOGRAPHY[countryName] ? countryName : 'India (Bharat)';
  if (!stateName || !districtName || !WORLD_GEOGRAPHY[resolvedCountry]?.[stateName]?.[districtName]) {
    const states = Object.keys(WORLD_GEOGRAPHY[resolvedCountry] || {});
    const st = states.includes(stateName) ? stateName : states[0];
    if (!st) return [];
    const dists = Object.keys(WORLD_GEOGRAPHY[resolvedCountry][st] || {});
    const dist = dists.includes(districtName) ? districtName : dists[0];
    if (!dist) return [];
    return Object.keys(WORLD_GEOGRAPHY[resolvedCountry][st][dist] || {});
  }
  return Object.keys(WORLD_GEOGRAPHY[resolvedCountry][stateName][districtName]);
};

export const getGramPanchayats = (countryName = 'India (Bharat)', stateName, districtName, cityName) => {
  const resolvedCountry = WORLD_GEOGRAPHY[countryName] ? countryName : 'India (Bharat)';
  if (
    !stateName ||
    !districtName ||
    !cityName ||
    !WORLD_GEOGRAPHY[resolvedCountry]?.[stateName]?.[districtName]?.[cityName]
  ) {
    const states = Object.keys(WORLD_GEOGRAPHY[resolvedCountry] || {});
    const st = states.includes(stateName) ? stateName : states[0];
    if (!st) return [];
    const dists = Object.keys(WORLD_GEOGRAPHY[resolvedCountry][st] || {});
    const dist = dists.includes(districtName) ? districtName : dists[0];
    if (!dist) return [];
    const cities = Object.keys(WORLD_GEOGRAPHY[resolvedCountry][st][dist] || {});
    const cty = cities.includes(cityName) ? cityName : cities[0];
    if (!cty) return [];
    return WORLD_GEOGRAPHY[resolvedCountry][st][dist][cty] || [];
  }
  return WORLD_GEOGRAPHY[resolvedCountry][stateName][districtName][cityName];
};
